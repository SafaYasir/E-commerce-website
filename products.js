// ==========================================
// ADD TO CART
// ==========================================

function addToCart(id){

    let product = products.find(function(item){

        return item.id === id;

    });


    cart.push(product);


    updateCart();


    document
        .getElementById("cart")
        .scrollIntoView({
            behavior:"smooth"
        });

}



// ==========================================
// UPDATE CART
// ==========================================

function updateCart(){

    let cartItems =
        document.getElementById("cartItems");


    let cartTotal =
        document.getElementById("cartTotal");


    if(cart.length === 0){

        cartItems.innerHTML = `

            <p class="empty-cart">
                Your cart is empty.
            </p>

        `;

        cartTotal.textContent = "0";

        return;

    }


    let total = 0;

    cartItems.innerHTML = "";


    for(let i = 0; i < cart.length; i++){

        total += cart[i].price;


        cartItems.innerHTML += `

            <div class="cart-item">

                <img
                    src="${cart[i].image}"
                    alt="${cart[i].name}"
                >


                <div class="cart-info">

                    <h3>
                        ${cart[i].name}
                    </h3>

                    <p>
                        £${cart[i].price}
                    </p>

                </div>


                <button
                    class="remove-btn"
                    onclick="removeFromCart(${i})">

                    Remove

                </button>

            </div>

        `;

    }


    cartTotal.textContent =
        total.toFixed(2);

}



// ==========================================
// REMOVE FROM CART
// ==========================================

function removeFromCart(index){

    cart.splice(index,1);

    updateCart();

}



// ==========================================
// HEART
// ==========================================

function likeProduct(button){

    let icon =
        button.querySelector("i");


    icon.classList.toggle("fa-regular");

    icon.classList.toggle("fa-solid");

}



// ==========================================
// ORDER DONE → WHATSAPP
// ==========================================

function orderDone(){

    if(cart.length === 0){

        alert(
            "Please add a product to your cart first."
        );

        return;

    }


    let message =
        "Hello! I want to order:%0A%0A";


    let total = 0;


    for(let i = 0; i < cart.length; i++){

        message +=
            `${i + 1}. ${cart[i].name} - £${cart[i].price}%0A`;

        total += cart[i].price;

    }


    message +=
        `%0ATotal: £${total.toFixed(2)}`;


    // AAPKA WHATSAPP NUMBER

    let whatsappNumber =
        "923153500874";


    let whatsappURL =
        `https://wa.me/${whatsappNumber}?text=${message}`;


    window.open(
        whatsappURL,
        "_blank"
    );

}